CREATE TABLE product_category_submission (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    normalized_product VARCHAR(255) NOT NULL,
    places_type VARCHAR(255) NOT NULL,
    submitted_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT product_category_submission_pkey PRIMARY KEY (id)
);

CREATE INDEX idx_normalized_product ON product_category_submission (normalized_product);
